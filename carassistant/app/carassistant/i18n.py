def translator(lang: str, charge: bool = False) -> Callable[..., str]:
    primary = CATALOGS.get(lang, EN)

    def t(key: str, **kwargs) -> str:
        if charge:
            key = CHARGE_KEYS.get(key, key)
        text = primary.get(key) or EN.get(key) or key
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, IndexError, ValueError):
                return text
        return text

    return t
