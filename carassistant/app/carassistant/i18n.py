CATALOGS: dict[str, dict[str, str]] = {"en": EN, "de": DE}
# code -> display name (in that language), date format (strftime) and text direction ("ltr" / "rtl")
LANGUAGES: dict[str, dict[str, str]] = {
    "en": {"name": "English", "date": "%Y-%m-%d", "dir": "ltr"},
    "de": {"name": "Deutsch", "date": "%d.%m.%Y", "dir": "ltr"},
}
LOCALES_DIR = Path(__file__).parent / "locales"
_CODE = re.compile(r"^[a-z]{2,3}(-[a-z0-9]{2,8})?$")


def load_locales(folder: Path = LOCALES_DIR) -> list[str]:
    """Add every ``locales/<code>.json`` as a language. A new language is just a new file (docs/translating.md).

    Keys starting with ``_`` are metadata: ``_name`` (name of the language in itself), ``_date`` (strftime), ``_dir`` (ltr/rtl).
    """
    added: list[str] = []
    for path in sorted(folder.glob("*.json")) if folder.is_dir() else []:
        code = path.stem
        if code in ("en", "de") or not _CODE.match(code):
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if not isinstance(data, dict):
            continue
        CATALOGS[code] = {k: v for k, v in data.items() if not k.startswith("_") and isinstance(v, str)}
        LANGUAGES[code] = {
            "name": str(data.get("_name") or code),
            "date": str(data.get("_date") or "%Y-%m-%d"),
            "dir": "rtl" if data.get("_dir") == "rtl" else "ltr",
        }
        added.append(code)
    return added


load_locales()


